function hash32(seed: string): number {
  let h = 2166136261;
  for (let i = 0; i < seed.length; i++) {
    h ^= seed.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

export function emojiAvatar(seed: string): string {
  const s = (seed || "?").trim().toLowerCase() || "?";
  return FACES[hash32(s) % FACES.length];
}
