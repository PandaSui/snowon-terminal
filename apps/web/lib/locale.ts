export function t(locale: Locale, key: string, vars?: Record<string, string | number>): string {
  let s = dict[locale]?.[key] ?? dict.zh[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replaceAll(`{${k}}`, String(v));
    }
  }
  return s;
}

export function formatTimeAgo(iso: string, locale: Locale): string {
  const raw = iso.includes("T") ? iso : iso.replace(" ", "T");
  const ts = new Date(raw).getTime();
  if (!Number.isFinite(ts)) return "-";
  const s = Math.max(1, Math.floor((Date.now() - ts) / 1000));
  if (s < 60) return t(locale, "agoSec", { n: s });
  if (s < 3600) return t(locale, "agoMin", { n: Math.floor(s / 60) });
  if (s < 86400) return t(locale, "agoHour", { n: Math.floor(s / 3600) });
  return t(locale, "agoDay", { n: Math.floor(s / 86400) });
}
